// Keeps three of Herdr's own mods current with our small changes applied.
// On every start it regenerates mods/<to>/ from Herdr's latest mods/<from>/
// plus the patch, so Herdr's fixes to those mods still reach us. The
// herdr-plus layout points its blocks at the generated copies.
// If Herdr changed the patched code (an anchor is gone), the copy becomes
// Herdr's unpatched mod and a warning says which patch needs updating.
// When a copy that was already there changes (usually after a Herdr update),
// it asks for a restart: Herdr reloads a running mod in place, which can leave
// it half-updated (0.1.16's tab bar ignored swipes until a restart).
// Runs as a 0 px block in layouts/herdr-plus.json. Log: ~/.config/herdr-app/.mod-patches.log
import { View, div } from "gpui-kit";
import { appHome, notify } from "herdr";
import * as fs from "fs/promises";

// Each `replace` pair must match Herdr's file exactly once.
const PATCHES = [
  {
    from: "workspace-chrome",
    to: "workspace-chrome-synced",
    why: "Templates row in the sidebar footer instead of Add machine (Settings > Machines still adds one)",
    replace: [[
      `\n        .child(row("machine", "plus", "Add machine", true, () => run("mod.open", { name: "machine-add" })));`,
      `\n        .child(h_flex().id("templates").h(28).px(8).gap(9).items_center().rounded(8).when(collapsed, el => el.relative().w(32).px(0).justify_center().tooltip("Templates")).text_color(t.muted).hover(s => s.bg(t.hover).text_color(t.foreground)).cursor_pointer().on_click(() => run("mod.open", { name: "templates" })).child(svg("mods/templates/templates.svg").size(14)).when(!collapsed, el => el.child("Templates")));`,
    ]],
  },
  {
    from: "workspace-status",
    to: "workspace-status-synced",
    why: "no ⌘⇧P commands hint (the keep-awake cup sits there instead)",
    replace: [[
      `      .child(div().id("palette").text_color(t.dim).on_click(() => run("app.palette")).child(this.hint(t)));`,
      `;`,
    ]],
  },
  {
    from: "tabs",
    to: "tabs-synced",
    why: "a Citations button (mods/cite) beside Files and Changes, opening the cite panel in the same stack",
    replace: [
      [
        `    const enabled = shared("workspace.panels") ?? ["files", "changes"];`,
        `    const enabled = [...(shared("workspace.panels") ?? ["files", "changes"]), "cite"];\n    const cites = (shared("cite.items") ?? []).length;`,
      ],
      [
        `      .when(enabled.includes("changes"), el => el.child(panelButton("changes", "Changes", "mods/changes/changes.svg")))`,
        `      .when(enabled.includes("changes"), el => el.child(panelButton("changes", "Changes", "mods/changes/changes.svg")))\n      .when(enabled.includes("cite"), el => el.child(panelButton("cite", cites ? \`Citations \${cites}\` : "Citations", "mods/cite/quote.svg")))`,
      ],
    ],
  },
];

// Returns { applied, changed }: applied false means the copy is Herdr's
// unpatched mod; changed means an existing copy was rewritten.
async function regenerate(home, p) {
  const shipped = await fs.readFile(`${home}/mods/${p.from}/main.js`, "utf8");
  let code = shipped;
  let applied = true;
  for (const [find, put] of p.replace) {
    if (code.split(find).length !== 2) { applied = false; break; }
    code = code.replace(find, () => put);
  }
  if (!applied) code = shipped;
  const header = applied
    ? `// Generated by mods/mod-patches from Herdr's mods/${p.from} on every start: ${p.why}.\n`
    : `// Generated by mods/mod-patches: Herdr's mods/${p.from} UNPATCHED (its code changed; update PATCHES).\n`;
  const manifest = JSON.parse(await fs.readFile(`${home}/mods/${p.from}/mod.json`, "utf8"));
  const dir = `${home}/mods/${p.to}`;
  await fs.mkdir?.(dir, { recursive: true }).catch(() => {});
  // mod.json first: a folder Herdr sees without one gets docked into the layout.
  const files = [["mod.json", JSON.stringify(manifest, null, 2) + "\n"], ["main.js", `${header}// Don't edit: change PATCHES in mods/mod-patches/main.js.\n${code}`]];
  let changed = false;
  for (const [name, text] of files) {
    const have = await fs.readFile(`${dir}/${name}`, "utf8").catch(() => null);
    if (have === text) continue;
    if (have !== null) changed = true;
    await fs.writeFile(`${dir}/${name}`, text);
  }
  return { applied, changed };
}

export default class ModPatches extends View {
  init(_props, cx) {
    cx.spawn(async () => {
      const home = appHome();
      const lines = [];
      const updated = [];
      for (const p of PATCHES) {
        try {
          const { applied: ok, changed } = await regenerate(home, p);
          if (changed) updated.push(p.from);
          lines.push(`${p.to}: ${ok ? "patched" : "UNPATCHED, anchor gone"}${changed ? ", rewritten" : ""}`);
          if (!ok) notify({ title: `Patch skipped: ${p.from}`, body: `Herdr changed mods/${p.from}; using its own version. Update PATCHES in mods/mod-patches.`, level: "warning", timeout: 15000 });
        } catch (e) {
          lines.push(`${p.to}: error ${e?.message ?? e}`);
          notify({ title: `Mod patch failed: ${p.from}`, body: String(e?.message ?? e), level: "error" });
        }
      }
      if (updated.length) notify({ title: "Restart Herdr", body: `Herdr's ${updated.join(", ")} changed and the patched copies were rewritten. Quit (⌘Q) and reopen so they load cleanly.`, level: "info", timeout: 20000 });
      await fs.writeFile(`${home}/.mod-patches.log`, `${new Date().toISOString()}\n${lines.join("\n")}\n`).catch(() => {});
    });
  }

  render() {
    return div();
  }
}
